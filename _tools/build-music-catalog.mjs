#!/usr/bin/env node
// Regenerates js/music-catalog.js (PUBLIC: song ids + ALL CAPS titles only — never download URLs) from the
// server-only source of truth supabase/functions/_shared/music-catalog.ts.
// Run after editing the catalog:  node _tools/build-music-catalog.mjs
// (Node >= 22.18 strips TypeScript types natively.) "_tools" is underscore-prefixed so GitHub Pages never serves it.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { MUSIC_CATALOG, PUPPY_SONG_IDS } from "../supabase/functions/_shared/music-catalog.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const puppy = new Set(PUPPY_SONG_IDS);
const list = MUSIC_CATALOG.map((s) => (puppy.has(s.id) ? { id: s.id, t: s.title, p: 1 } : { id: s.id, t: s.title }));
const body = "/* GENERATED by _tools/build-music-catalog.mjs — do not edit by hand.\n" +
  "   Public song list for the pick-your-songs checkout (ids + titles only; downloads are served\n" +
  "   exclusively by the verify-music-purchase edge function after a paid Stripe session). */\n" +
  "window.HM_MUSIC_CATALOG = " + JSON.stringify(list) + ";\n";
writeFileSync(join(root, "js", "music-catalog.js"), body);
console.log("js/music-catalog.js:", list.length, "songs (", list.filter((s) => s.p).length, "PuppySongs )");
